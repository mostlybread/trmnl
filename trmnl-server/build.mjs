// Builds dist/worker.js, the one file to paste into Cloudflare.
// It reads both plugins straight from ../trmnl-transport and ../trmnl-weather,
// so a change to a plugin only needs a rebuild here.
//
//   npm install && node build.mjs

import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const PLUGINS = { transport: '../trmnl-transport', weather: '../trmnl-weather', radar: '../trmnl-radar', forecast: '../trmnl-forecast' };

// Just enough YAML for the settings.yml files trmnlp writes.
function readSettings(text) {
  const lines = text.split('\n');
  const scalar = (key) => {
    const i = lines.findIndex((l) => l.startsWith(`${key}:`));
    if (i < 0) return '';
    const rest = lines[i].slice(key.length + 1).trim();
    if (rest === '|-' || rest === '|') {
      const block = [];
      for (let j = i + 1; j < lines.length && /^\s+\S/.test(lines[j]); j++) block.push(lines[j].trim());
      return block.join('\n');
    }
    return rest.replace(/^'(.*)'$/, '$1').replace(/^"(.*)"$/, '$1');
  };
  const fields = {};
  let current = null;
  for (const line of lines) {
    let m = line.match(/^- keyname:\s*(\S+)/);
    if (m) { current = m[1]; fields[current] = ''; continue; }
    m = line.match(/^\s+default:\s*(.*)$/);
    if (m && current) fields[current] = m[1].trim().replace(/^'(.*)'$/, '$1').replace(/^"(.*)"$/, '$1');
  }
  return {
    polling_urls: scalar('polling_url').split('\n').map((u) => u.trim()).filter(Boolean),
    polling_headers: scalar('polling_headers'),
    defaults: fields,
  };
}

const plugins = {};
for (const [name, dir] of Object.entries(PLUGINS)) {
  const src = join(here, dir, 'src');
  plugins[name] = {
    ...readSettings(readFileSync(join(src, 'settings.yml'), 'utf8')),
    shared: readFileSync(join(src, 'shared.liquid'), 'utf8'),
    full: readFileSync(join(src, 'full.liquid'), 'utf8'),
  };
}
writeFileSync(
  join(here, 'src/plugins.generated.js'),
  '// Generated by build.mjs from the two plugin folders. Do not edit.\n' +
    `export default ${JSON.stringify(plugins, null, 2)};\n`,
);

mkdirSync(join(here, 'dist'), { recursive: true });
export const options = {
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  banner: { js: '// TRMNL server for Cloudflare Workers. Built from trmnl-server/src by build.mjs; paste this whole file into the Worker editor.' },
  loader: { '.png': 'binary' },
};

await build({ ...options, entryPoints: [join(here, 'src/worker.js')], outfile: join(here, 'dist/worker.js') });
console.log('wrote dist/worker.js');
